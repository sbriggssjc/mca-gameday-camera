def generate_report_md(
    metadata: Dict[str, Any], metrics: Dict[str, Any], plays: List[Dict[str, Any]]
) -> str:
    lines: List[str] = []
    lines.append("# Game Report")
    lines.append("")
    lines.append(f"Team: {metadata.get('team_us', '')}")
    lines.append(f"Opponent: {metadata.get('opponent', '')}")
    lines.append(f"Date: {metadata.get('date', '')}")
    lines.append("")
    lines.append("## Summary")
    lines.append(
        f"Plays detected: {metrics['plays_detected']} (valid {metrics['valid_plays_used']})"
    )
    lines.append(
        f"Total clip runtime: {metrics['total_clip_runtime']:.1f} seconds"
    )
    if metrics["label_counts"]:
        lines.append("Label mix:")
        for label, cnt in metrics["label_counts"].items():
            lines.append(f"- {label}: {cnt}")
    lines.append("")

    wins = [p for p in plays if p.get("tag") == "WIN"]
    corrs = [p for p in plays if p.get("tag") == "CORRECTION"]
    lines.append("## Top Wins")
    for p in sorted(wins, key=lambda x: x.get("agg_grade", 0), reverse=True)[:5]:
        lines.append(
            f"- Play {p['play_id']} ({p.get('label', 'UNKNOWN')}) grade={p.get('agg_grade', 0):.2f}"
        )
    lines.append("")
    lines.append("## Top Corrections")
    for p in sorted(corrs, key=lambda x: x.get("agg_grade", 0))[:5]:
        lines.append(
            f"- Play {p['play_id']} ({p.get('label', 'UNKNOWN')}) grade={p.get('agg_grade', 0):.2f}"
        )

    lines.append("")
    lines.append("## Full Play Table")
    lines.append("play_id | start | end | label | grade | tag")
    lines.append("---|---|---|---|---|---")
    for p in plays:
        lines.append(
            f"{p['play_id']} | {p.get('start_s', 0):.2f} | {p.get('end_s', 0):.2f} | "
            f"{p.get('label', 'UNKNOWN')} | {p.get('agg_grade', '')} | {p.get('tag', '')}"
        )

    lines.append("")
    lines.append("## Data provenance")
    lines.append("Report generated by rich_summary.py")
    return "\n".join(lines)

