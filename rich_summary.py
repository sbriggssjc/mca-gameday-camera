def ingest_plays(
    plays_data: List[Dict[str, Any]],
    pred_data: List[Dict[str, Any]],
    grades_data: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Merge play, prediction and grading information into a single list."""

    plays: List[Dict[str, Any]] = []
    for idx, raw in enumerate(plays_data):
        play: Dict[str, Any] = dict(raw)
        play_id = find_field(play, ["play_id", "id", "index"]) or idx + 1
        play["play_id"] = int(play_id)

        start = find_field(
            play,
            ["start_s", "start", "start_time", "t0", "ts", "begin", "clip_start"],
        )
        end = find_field(
            play,
            ["end_s", "end", "end_time", "t1", "te", "finish", "clip_end"],
        )
        try:
            play["start_s"] = float(start)
            play["end_s"] = float(end)
        except Exception:
            play["start_s"] = math.nan
            play["end_s"] = math.nan
        plays.append(play)

    # merge prediction labels
    for idx, pred in enumerate(pred_data):
        pid = find_field(pred, ["play_id", "id"]) or idx + 1
        label = find_field(pred, ["label", "prediction", "formation"]) or "UNKNOWN"
        if 0 < int(pid) <= len(plays):
            plays[int(pid) - 1]["label"] = label

    # merge grades
    for idx, grade in enumerate(grades_data):
        pid = find_field(grade, ["play_id", "id"]) or idx + 1
        ag = find_field(grade, ["grade", "agg_grade"])
        if ag is None and isinstance(grade.get("grades"), dict):
            vals = [v for v in grade["grades"].values() if isinstance(v, (int, float))]
            ag = float(np.mean(vals)) if vals else None
        if 0 < int(pid) <= len(plays) and ag is not None:
            plays[int(pid) - 1]["agg_grade"] = float(ag)
        if 0 < int(pid) <= len(plays) and isinstance(grade.get("grades"), dict):
            plays[int(pid) - 1]["grades"] = grade["grades"]
    return plays


def get_video_info(video_path: Path) -> Tuple[float, float]:
    """Return ``(duration_seconds, fps)`` for ``video_path``."""

    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        raise FileNotFoundError(f"Unable to open video: {video_path}")
    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    frame_count = cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0
    duration = frame_count / fps if frame_count else 0
    cap.release()
    return float(duration), float(fps)


def normalize_windows(
    plays: List[Dict[str, Any]], video_duration: float, min_len: float
) -> Tuple[List[Dict[str, Any]], Dict[str, int], Dict[int, str], str]:
    """Normalize play start/end times and filter invalid windows.

    Parameters
    ----------
    plays:
        List of play dictionaries possibly containing various start/end keys.
    video_duration:
        Duration of the source video in seconds.
    min_len:
        Minimum allowed clip length in seconds.

    Returns
    -------
    (valid_plays, exclusion_stats, per_play_reasons, unit)
        ``valid_plays`` are mutated in-place with ``start_s``/``end_s`` fields
        normalised to seconds. ``exclusion_stats`` tallies the number of dropped
        rows per reason and ``per_play_reasons`` maps the original play index to
        the exclusion reason. ``unit`` describes whether timestamps were assumed
        to be in seconds or converted from milliseconds.
    """

    start_vals: List[float] = []
    for p in plays:
        start_raw = find_field(p, ["start_s", "start", "start_time", "t0", "ts", "begin", "clip_start"])
        try:
            if start_raw is not None:
                start_vals.append(float(start_raw))
        except Exception:
            continue
    median_start = float(np.median(start_vals)) if start_vals else 0.0
    unit = "seconds"
    factor = 1.0
    if median_start > video_duration * 1.2:
        unit = "milliseconds->seconds"
        factor = 0.001

    valid: List[Dict[str, Any]] = []
    exclusion_stats: Dict[str, int] = {}
    per_play_reasons: Dict[int, str] = {}

    for idx, play in enumerate(plays):
        s_raw = find_field(play, ["start_s", "start", "start_time", "t0", "ts", "begin", "clip_start"])
        e_raw = find_field(play, ["end_s", "end", "end_time", "t1", "te", "finish", "clip_end"])
        try:
            start = float(s_raw) * factor
            end = float(e_raw) * factor
        except Exception:
            per_play_reasons[idx] = "missing_time"
            exclusion_stats["missing_time"] = exclusion_stats.get("missing_time", 0) + 1
            continue
        start = max(0.0, min(video_duration, start))
        end = max(0.0, min(video_duration, end))
        if end <= start:
            per_play_reasons[idx] = "end_before_start"
            exclusion_stats["end_before_start"] = exclusion_stats.get("end_before_start", 0) + 1
            continue
        if end - start < min_len:
            per_play_reasons[idx] = "too_short"
            exclusion_stats["too_short"] = exclusion_stats.get("too_short", 0) + 1
            continue
        play["start_s"] = float(start)
        play["end_s"] = float(end)
        play["duration"] = float(end - start)
        valid.append(play)

    return valid, exclusion_stats, per_play_reasons, unit


def validate_plays(
    plays: List[Dict[str, Any]],
    *,
    duration: float,
    min_len: float = 3.0,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Split plays into valid and invalid lists after sanity checks."""

    valid: List[Dict[str, Any]] = []
    invalid: List[Dict[str, Any]] = []
    last_end = 0.0
    for play in sorted(plays, key=lambda p: p.get("start_s", 0)):
        start, end = play.get("start_s"), play.get("end_s")
        if start is None or end is None or math.isnan(start) or math.isnan(end):
            play["invalid_reason"] = "missing_time"
            invalid.append(play)
            continue
        start = max(0.0, float(start))
        end = min(duration, float(end))
        if end - start < min_len:
            play["invalid_reason"] = "too_short"
            invalid.append(play)
            continue
        if start < last_end:
            overlap = last_end - start
            if overlap > 0.75:
                start = last_end + 0.01
        last_end = end
        play["start_s"], play["end_s"] = start, end
        play["duration"] = end - start
        valid.append(play)
    return valid, invalid


def classify_plays(
    plays: List[Dict[str, Any]], wins_th: float, corrections_th: float
) -> None:
    for play in plays:
        grade = play.get("agg_grade")
        if grade is None:
            play["tag"] = "NEUTRAL"
        elif grade >= wins_th:
            play["tag"] = "WIN"
        elif grade <= corrections_th:
            play["tag"] = "CORRECTION"
        else:
            play["tag"] = "NEUTRAL"


