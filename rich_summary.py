def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Build rich film summaries")

    def clip_length(value: str) -> float:
        v = float(value)
        if v < 0.5:
            raise argparse.ArgumentTypeError("min-clip-sec must be >= 0.5")
        return v

    parser.add_argument("--video", required=True, help="MP4 path")
    parser.add_argument("--out", required=True, help="Pipeline output folder")
    parser.add_argument("--team")
    parser.add_argument("--opponent")
    parser.add_argument("--date")
    parser.add_argument("--wins-threshold", type=float, default=3.0)
    parser.add_argument("--corrections-threshold", type=float, default=2.0)
    parser.add_argument("--export-hudl", action="store_true")
    parser.add_argument("--per-player-cutups", action="store_true")
    parser.add_argument("--max-top", type=int, default=10)
    parser.add_argument("--min-clip-sec", type=clip_length, default=2.0)
    parser.add_argument("--dry-run", action="store_true", help="Skip clip rendering")
    parser.add_argument(
        "--pdf-engine",
        choices=["fpdf", "reportlab", "none"],
        default="reportlab",
        help="PDF rendering backend",
    )
    args = parser.parse_args(argv)

    video_path = Path(args.video)
    out_dir = Path(args.out)

    if not video_path.exists():
        print("Video not found", video_path)
        return 1

    # logging setup
    log_path = out_dir / "logs" / "rich_summary.log"
    ensure_dir(log_path.parent)
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
        handlers=[logging.FileHandler(log_path), logging.StreamHandler()],
    )

    duration, fps = get_video_info(video_path)
    logging.info("Video duration %.2fs @ %.2ffps", duration, fps)

    # metadata
    metadata_path = out_dir / "metadata.json"
    metadata: Dict[str, Any] = {}
    if metadata_path.exists():
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    if args.team:
        metadata["team_us"] = args.team
    if args.opponent:
        metadata["opponent"] = args.opponent
    if args.date:
        metadata["date"] = args.date
    metadata["video_path"] = str(video_path)
    ensure_dir(metadata_path.parent)
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    # ingest jsonls
    plays_data = read_jsonl(out_dir / "plays.jsonl")
    pred_data = read_jsonl(out_dir / "play_predictions.jsonl")
    grades_data = read_jsonl(out_dir / "grades.jsonl")
    plays = ingest_plays(plays_data, pred_data, grades_data)

    norm_plays, excl_stats, per_play_reasons, unit = normalize_windows(
        plays, duration, args.min_clip_sec
    )
    valid, invalid_post = validate_plays(
        norm_plays, duration=duration, min_len=args.min_clip_sec
    )

    invalid_norm = []
    for idx, reason in per_play_reasons.items():
        raw = dict(plays[idx])
        raw["invalid_reason"] = reason
        invalid_norm.append(raw)
    invalid = invalid_norm + invalid_post

    classify_plays(valid, args.wins_threshold, args.corrections_threshold)

    metrics = compute_metrics(valid, invalid)
    write_timeline_csv(valid, out_dir / "dashboards" / "timeline.csv")
    write_summary_json(metrics, out_dir / "dashboards" / "summary.json")

    report = {
        "video_duration": float(duration),
        "min_clip_sec": float(args.min_clip_sec),
        "unit": unit,
        "total_rows": len(plays),
        "valid_rows": len(valid),
        "exclusions": excl_stats,
        "examples": [
            {"idx": int(i), "reason": r, "raw": plays[int(i)]}
            for i, r in list(per_play_reasons.items())[:10]
        ],
    }
    report_path = out_dir / "sanity" / "validation_report.json"
    ensure_dir(report_path.parent)
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    logging.info(
        "Validation: %d/%d rows valid (unit=%s); exclusions=%s",
        len(valid),
        len(plays),
        unit,
        excl_stats,
    )

    md_text = generate_report_md(metadata, metrics, valid)
    md_path = out_dir / "reports" / "report.md"
    pdf_path = out_dir / "reports" / "report.pdf"
    write_md(md_text, md_path)

    generate_snapshots(
        video_path, valid, out_dir / "sanity" / "snapshots.jpg"
    )

    encoder = detect_encoder()

    # highlight clips -----------------------------------------------------
    if not args.dry_run:
        tmp_dir = out_dir / "clips" / "tmp"
        ensure_dir(tmp_dir)

        def build_clip_list(sel: List[Dict[str, Any]]) -> List[Path]:
            out_paths: List[Path] = []
            for p in sel:
                text = f"#{p['play_id']} | {p.get('label', 'UNKNOWN')} | grade:{p.get('agg_grade',0):.2f} | {p.get('tag')}"
                tmp = tmp_dir / f"clip_{p['play_id']}.mp4"
                ok = cut_clip(
                    video_path, p["start_s"], p["end_s"], text, tmp, encoder
                )
                if not ok:
                    logging.error("Failed to render clip %s", tmp)
                    return []
                out_paths.append(tmp)
            return out_paths

        # team highlights: top plays by grade but max 2 per label
        top_sorted = sorted(valid, key=lambda x: x.get("agg_grade", 0), reverse=True)
        label_counter: Dict[str, int] = {}
        highlights: List[Dict[str, Any]] = []
        for p in top_sorted:
            label = p.get("label", "UNKNOWN")
            if label_counter.get(label, 0) >= 2:
                continue
            label_counter[label] = label_counter.get(label, 0) + 1
            highlights.append(p)
            if len(highlights) >= args.max_top:
                break
        highlight_clips = build_clip_list(highlights)
        concat_clips(
            highlight_clips,
            out_dir / "clips" / "highlights" / "team_highlights.mp4",
            encoder,
        )

        wins = [p for p in valid if p.get("tag") == "WIN"]
        wins = sorted(wins, key=lambda x: x.get("agg_grade", 0), reverse=True)[
            : args.max_top
        ]
        win_clips = build_clip_list(wins)
        concat_clips(
            win_clips,
            out_dir / "clips" / "wins" / "top_wins.mp4",
            encoder,
        )

        corr = [p for p in valid if p.get("tag") == "CORRECTION"]
        corr = sorted(corr, key=lambda x: x.get("agg_grade", 0))[: args.max_top]
        corr_clips = build_clip_list(corr)
        concat_clips(
            corr_clips,
            out_dir / "clips" / "corrections" / "top_corrections.mp4",
            encoder,
        )

        # per-player cutups ------------------------------------------------
        if args.per_player_cutups:
            vis_map_path = out_dir / "config" / "player_visual_ids.yaml"
            jersey_map: Dict[str, Any] = {}
            if vis_map_path.exists():
                jersey_map = yaml.safe_load(vis_map_path.read_text()) or {}
            for jersey in sorted(jersey_map.keys()):
                player_plays = [
                    p
                    for p in valid
                    if jersey in (p.get("players") or [])
                    or jersey in (p.get("player_ids") or [])
                ]
                if not player_plays:
                    continue
                clips = build_clip_list(player_plays)
                concat_clips(
                    clips,
                    out_dir
                    / "clips"
                    / "players"
                    / jersey
                    / f"{jersey}_cutups.mp4",
                    encoder,
                )

    # HUDL export --------------------------------------------------------
    if args.export_hudl:
        export_hudl_csv(
            valid,
            out_dir / "hudl_export" / "hudl_export.csv",
        )

    # PDF rendering ------------------------------------------------------
    if args.pdf_engine == "reportlab":
        render_pdf_reportlab(md_path, pdf_path)
    elif args.pdf_engine == "fpdf":
        try:
            render_pdf_fpdf(md_path, pdf_path)
        except Exception as exc:
            log.warning("FPDF failed (%s); falling back to ReportLab", exc)
            render_pdf_reportlab(md_path, pdf_path)
    else:
        log.info("PDF rendering skipped")

    # Final output -------------------------------------------------------
    print("Summary written to", out_dir)
    print("Valid plays:", metrics["valid_plays_used"])
    if pdf_path.exists():
        print("Report:", pdf_path)
    else:
        print("Report: PDF not generated")
    if metrics["valid_plays_used"] < 5:
        print(
            "ACTIONABLE HINTS: very few valid plays detected; check validation_report.json and consider lowering --min-clip-sec"
        )

    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry
    raise SystemExit(main())



def _encoder_flags(enc):
    return ENCODER_OPTS.get(enc or "libx264", ENCODER_OPTS["libx264"])

def _splice_encoder(cmd:list, enc:str)->list:
    if "--ENCODER--" in cmd:
        ix = cmd.index("--ENCODER--")
        return cmd[:ix] + _encoder_flags(enc) + cmd[ix+1:]
    return cmd

def _ensure_codec_flags(cmd:list, encoder:str)->list:
    cmd = cmd[:]
    has_cv = any(x == "-c:v" for x in cmd)
    has_ca = any(x == "-c:a" for x in cmd)
    # Insert before the final output path (last token)
    insert_at = len(cmd)-1 if len(cmd)>=2 else len(cmd)
    if not has_cv:
        cmd[insert_at:insert_at] = ENCODER_OPTS.get(encoder, ENCODER_OPTS["libx264"])
        insert_at = len(cmd)-1
    if not has_ca:
        cmd[insert_at:insert_at] = AUDIO_OPTS
        insert_at = len(cmd)-1
    # Shortest avoids audio/video length mismatch hangs
    if "-shortest" not in cmd:
        cmd.insert(insert_at, "-shortest")
    return cmd

def _run_ffmpeg_command(cmd:list, timeout:int=120):
    enc = detect_encoder()
    cmd = _ensure_codec_flags(cmd, enc)
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        ok = (proc.returncode == 0)
        return ok, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired as e:
        return False, "", f"ffmpeg timeout after {timeout}s: {e}"
    except Exception as e:
        return False, "", f"ffmpeg error: {e}"
