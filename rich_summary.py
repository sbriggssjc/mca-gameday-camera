def _soften_tokens(text, max_run=80):
    # Insert a zero-width space after every max_run non-space chars
    pat = re.compile(r'\S{' + str(max_run) + r'}')
    return pat.sub(lambda m: m.group(0) + '\u200b', text)
def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    """Read a ``.jsonl`` file and return a list of dictionaries."""

    items: List[Dict[str, Any]] = []
    if not path.exists():
        logging.warning("%s missing", path)
        return items
    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                items.append(json.loads(line))
            except json.JSONDecodeError as exc:
                logging.debug("Skipping bad JSON line in %s: %s", path, exc)
    logging.debug("Loaded %d rows from %s", len(items), path)
    return items


def find_field(d: Dict[str, Any], names: Iterable[str]) -> Any:
    """Return the value for the first key in ``names`` present in ``d``.

    The check is case-insensitive and will match "start_s" against keys such as
    "Start" or "START_S".
    """

    lowered = {k.lower(): k for k in d.keys()}
    for name in names:
        key = lowered.get(name.lower())
        if key is not None:
            return d[key]
    return None


