def hudl_time(sec: float) -> str:
    m = int(sec // 60)
    s = sec - m * 60
    return f"{m:02d}:{s:06.3f}"


def export_hudl_csv(plays: List[Dict[str, Any]], path: Path) -> None:
    ensure_dir(path.parent)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["Label", "Start Time", "End Time", "Duration", "Notes", "Playlist"])
        for p in plays:
            playlist = (
                "Wins" if p.get("tag") == "WIN" else "Corrections" if p.get("tag") == "CORRECTION" else "Highlights"
            )
            writer.writerow(
                [
                    p.get("label", "UNKNOWN"),
                    hudl_time(p["start_s"]),
                    hudl_time(p["end_s"]),
                    f"{p['duration']:.2f}",
                    "",
                    playlist,
                ]
            )


