def compute_metrics(valid: List[Dict[str, Any]], invalid: List[Dict[str, Any]]) -> Dict[str, Any]:
    label_counts: Dict[str, int] = {}
    for p in valid:
        label = p.get("label", "UNKNOWN")
        label_counts[label] = label_counts.get(label, 0) + 1
    total_runtime = sum(p.get("duration", 0.0) for p in valid)
    win_count = sum(1 for p in valid if p.get("tag") == "WIN")
    corr_count = sum(1 for p in valid if p.get("tag") == "CORRECTION")
    metrics = {
        "plays_detected": len(valid) + len(invalid),
        "valid_plays_used": len(valid),
        "invalid_plays": len(invalid),
        "total_clip_runtime": total_runtime,
        "label_counts": label_counts,
        "wins": win_count,
        "corrections": corr_count,
    }
    return metrics


