"""rich_summary.py

Entry point for building a "rich" post-game summary from an existing
film-processing pipeline.

Usage
-----
```
python rich_summary.py --video VIDEO.mp4 --out OUT_DIR [options]
```

The script expects the ``OUT_DIR`` to contain JSONL artefacts generated by the
earlier pipeline (``plays.jsonl``, ``tracking.jsonl`` etc.).  It validates the
play windows against the supplied video, computes basic metrics and produces a
coach-facing markdown/PDF report together with highlight reels.  Only a subset
of the full specification is implemented here but the structure is designed to
be robust and easily extensible.

Common issues
-------------
* **FFmpeg missing** – ensure ``ffmpeg`` is available on ``$PATH``.
* **Invalid JSONL** – each line in ``*.jsonl`` files must be valid JSON.
* **No valid plays** – if play start/end times are missing or fall outside the
  video duration the script will exit with a non‑zero status.

This module is intentionally self‑contained so it can be copied into other
projects if desired.
"""


