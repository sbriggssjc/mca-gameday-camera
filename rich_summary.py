def cut_clip(
    video: Path,
    start: float,
    end: float,
    text: str,
    out_path: Path,
    encoder: str,
) -> bool:
    draw = (
        "drawtext=fontfile=/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf:"
        f"text='{text}':x=10:y=h-40:fontsize=24:fontcolor=white:box=1:boxcolor=0x00000099"
    )
    cmd = [
        "ffmpeg",
        "-y",
        "-ss",
        f"{start:.2f}",
        "-to",
        f"{end:.2f}",
        "-i",
        str(video),
        "-vf",
        draw,
        "-c:v",
        encoder,
        "-c:a",
        "copy",
        str(out_path),
    ]
    ret, _, _ = _run_ffmpeg_command(cmd, timeout=120)
    return ret == 0


def concat_clips(clips: List[Path], out_path: Path, encoder: str) -> bool:
    if not clips:
        return False
    ensure_dir(out_path.parent)
    list_file = out_path.parent / "concat_list.txt"
    with list_file.open("w", encoding="utf-8") as f:
        for clip in clips:
            f.write(f"file '{clip}'\n")
    cmd = [
        "ffmpeg",
        "-y",
        "-f",
        "concat",
        "-safe",
        "0",
        "-i",
        str(list_file),
        "-c",
        "copy",
        str(out_path),
    ]
    ret, _, _ = _run_ffmpeg_command(cmd, timeout=120)
    list_file.unlink(missing_ok=True)
    return ret == 0


