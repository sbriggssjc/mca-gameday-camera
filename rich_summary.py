def render_pdf_fpdf(md_path: Path, pdf_path: Path) -> None:
    """Render ``md_path`` into ``pdf_path`` using FPDF."""
    if FPDF is None:  # dependency missing
        raise RuntimeError("FPDF library not available")
    txt = md_path.read_text(encoding="utf-8", errors="replace")
    ensure_dir(pdf_path.parent)
    pdf = FPDF()
    pdf.set_auto_page_break(True, 15)
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=12)
    pdf.set_left_margin(12)
    pdf.set_right_margin(12)
    pdf.set_font("Helvetica", size=12)
    for line in txt.splitlines():
        pdf.multi_cell(0, 8, _soften_tokens(line))
    pdf.output(str(pdf_path))
    log.info("FPDF PDF written: %s", pdf_path)


def render_pdf_reportlab(md_path: Path, pdf_path: Path) -> None:
    """Render ``md_path`` into ``pdf_path`` using ReportLab."""
    try:
        from reportlab.platypus import Preformatted, SimpleDocTemplate
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.units import mm
    except Exception as exc:  # pragma: no cover - dependency issues
        log.warning("ReportLab not available: %s", exc)
        return

    txt = md_path.read_text(encoding="utf-8", errors="replace")
    ensure_dir(pdf_path.parent)
    doc = SimpleDocTemplate(
        str(pdf_path),
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )
    style = getSampleStyleSheet()["Code"]
    doc.build([Preformatted(txt, style)])
    log.info("ReportLab PDF written: %s", pdf_path)


def generate_snapshots(video_path: Path, plays: List[Dict[str, Any]], out_path: Path) -> None:
    ensure_dir(out_path.parent)
    cap = cv2.VideoCapture(str(video_path))
    thumbs: List[np.ndarray] = []
    for play in plays:
        cap.set(cv2.CAP_PROP_POS_MSEC, play["start_s"] * 1000)
        ok, frame = cap.read()
        if not ok:
            continue
        cv2.putText(
            frame,
            f"#{play['play_id']}",
            (10, 40),
            cv2.FONT_HERSHEY_SIMPLEX,
            1.0,
            (0, 255, 0),
            2,
            cv2.LINE_AA,
        )
        thumbs.append(frame)
    cap.release()
    if not thumbs:
        return
    cols = int(math.ceil(math.sqrt(len(thumbs))))
    rows = int(math.ceil(len(thumbs) / cols))
    h, w, _ = thumbs[0].shape
    grid = np.zeros((rows * h, cols * w, 3), dtype=thumbs[0].dtype)
    for idx, img in enumerate(thumbs):
        r = idx // cols
        c = idx % cols
        grid[r * h : (r + 1) * h, c * w : (c + 1) * w] = img
    cv2.imwrite(str(out_path), grid)


